/** \file
  \brief Test prints generated by the firmware, see calibration.h.

  The moves go through the same path as G1 (bed leveling included), E
  relative, like the firmware retract: the E coordinate of the host is
  restored after each move, so a print continues afterwards as if nothing
  happened. M410 stops a test print.
*/

