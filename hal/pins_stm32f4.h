/** \file
  \brief Arduino-style pin names for STM32F401 / STM32F411.

  Generated table, do not edit by hand. Every pin name, e.g. PA_5, is a bare
  token which is never defined itself. Properties are looked up by token
  pasting through the PIN_xxx() helpers below, so all pin operations resolve
  at compile time into a single register access:

    PIN_PORT(PA_5)     -> GPIOA                  (GPIO_TypeDef *)
    PIN_NUM(PA_5)      -> 5                      (bit number in the port)
    PIN_ID(PA_5)       -> 0x05                   (port index << 4 | bit)
    PIN_ADC(PA_5)      -> 5                      (ADC1 channel or ADC_NONE)
    PIN_TIMER(PA_5)    -> TIM2_BASE              (PWM timer base or 0)
    PIN_CHANNEL(PA_5)  -> 1                      (timer channel 1..4 or 0)
    PIN_AF(PA_5)       -> 1                      (alternate function number)
    PIN_COMPL(PA_5)    -> 0                      (1 = complementary CHxN output)

  Both naming styles known from the Arduino STM32 core are accepted:
  PA_5 (PinName style) and PA5 (pin alias style). Pins not present in a given
  package (e.g. PB11 or PC0 on the 48-pin Blackpill) simply must not be used.

  TIM5 is reserved for the step timer and therefore never listed as PWM timer.
*/

