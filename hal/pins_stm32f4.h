/* Two-level concatenation so that aliases like PA5 get expanded first. */
#define PIN_CAT_(a, b)    a ## b
#define PIN_CAT(a, b)     PIN_CAT_(a, b)

#define PIN_PORT(p)       PIN_CAT(p, _PORT)
#define PIN_NUM(p)        PIN_CAT(p, _PIN)
#define PIN_ID(p)         PIN_CAT(p, _ID)
#define PIN_ADC(p)        PIN_CAT(p, _ADC)
#define PIN_TIMER(p)      PIN_CAT(p, _TIMER)
#define PIN_CHANNEL(p)    PIN_CAT(p, _CHANNEL)
#define PIN_AF(p)         PIN_CAT(p, _AF)
#define PIN_COMPL(p)      PIN_CAT(p, _COMPL)

/// Runtime helpers working on a PIN_ID() value.
#define PIN_ID_PORT(id)   ((GPIO_TypeDef *)(GPIOA_BASE + (((id) >> 4) & 0x0FU) * 0x400UL))
#define PIN_ID_NUM(id)    ((id) & 0x0FU)

